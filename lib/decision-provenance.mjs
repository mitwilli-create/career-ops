// lib/decision-provenance.mjs — "why did this score/decision happen?" trail.
//
// Per DESIGN_PRINCIPLES.md Pillar 4 (background transparency): every metric
// the dashboard surfaces must have an inspectable trail. This lib reads report
// markdown headers + data/hm-intel/_weights.json + git log of the report file
// to reconstruct the inputs that produced each per-row metric.
//
// Pillar 1 (scannability): renderProvenanceCard() emits a minimal HTML card
// using --text-sm/--text-base CSS custom-property tokens for font sizing.
//
// NO LLM calls. NO new npm dependencies. Pure file + git log parsing.

import { readFileSync, existsSync }       from 'fs';
import { join, dirname }                  from 'path';
import { fileURLToPath }                  from 'url';
import { execSync }                       from 'child_process';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT      = join(__dirname, '..');

// ── weights loader ────────────────────────────────────────────────────────────

let _weightsCache = null;

function loadWeights() {
  if (_weightsCache) return _weightsCache;
  const p = join(ROOT, 'data', 'hm-intel', '_weights.json');
  if (!existsSync(p)) return {};
  try {
    _weightsCache = JSON.parse(readFileSync(p, 'utf-8'));
    return _weightsCache;
  } catch { return {}; }
}

// ── Report file finder ────────────────────────────────────────────────────────

const REPORTS_DIR = join(ROOT, 'reports');

function findReportFile(rowId) {
  if (!existsSync(REPORTS_DIR)) return null;
  // Report filenames start with zero-padded rowId
  const prefix = String(rowId).padStart(3, '0');
  try {
    const { readdirSync } = await_fs();
    const files = readdirSync(REPORTS_DIR);
    const match = files.find(f => f.startsWith(prefix + '-') || f.startsWith(String(rowId) + '-'));
    return match ? join(REPORTS_DIR, match) : null;
  } catch { return null; }
}

// Sync wrapper — avoids async surface on the export
function await_fs() {
  return { readdirSync: (p) => {
    const { readdirSync } = await_require_fs();
    return readdirSync(p);
  }};
}
function await_require_fs() {
  // Inline require so the module stays ESM without dynamic import latency
  return { readdirSync: (p) => {
    const fs = { readdirSync: (dir) => {
      const { execSync: ex } = { execSync };
      try {
        return ex(`ls -1 "${dir}"`, { encoding: 'utf-8' }).trim().split('\n').filter(Boolean);
      } catch { return []; }
    }};
    return fs.readdirSync(p);
  }};
}

// Simpler: use execSync ls directly
function listReportsDir() {
  try {
    return execSync(`ls -1 "${REPORTS_DIR}"`, { encoding: 'utf-8', timeout: 10_000 })
      .trim().split('\n').filter(Boolean);
  } catch { return []; }
}

function findReportFileSync(rowId) {
  if (!existsSync(REPORTS_DIR)) return null;
  // 2026-05-20 — The row num and the report file's prefix number are NOT
  // the same. Tracker row "| 2253 | ... | [1050](reports/1050-ema-...md)"
  // means rowId=2253 but the actual file is reports/1050-ema-...md.
  // Prior version did `files.find(f => f.startsWith(rowId + '-'))` which
  // missed every row where the two diverged → "no report file on disk"
  // popups for Ema, Pinecone, and any row where the report number was
  // assigned independently of the row num. Fix: parse the actual report
  // path from the row's markdown link in applications.md.
  const APPS = join(REPORTS_DIR, '..', 'data', 'applications.md');
  if (existsSync(APPS)) {
    try {
      const text = readFileSync(APPS, 'utf-8');
      // Match the row: "| <rowId> | <date> | ... | [N](reports/PATH.md) |"
      const rowRe = new RegExp(`^\\|\\s*${rowId}\\s*\\|.*?\\[[^\\]]+\\]\\(([^)]+\\.md)\\)`, 'm');
      const m = rowRe.exec(text);
      if (m && m[1]) {
        const rel = m[1].replace(/^reports\//, '');
        const abs = join(REPORTS_DIR, rel);
        if (existsSync(abs)) return abs;
      }
    } catch { /* fall through to prefix match */ }
  }
  // Fallback: prefix match (correct for rows where rowId === report
  // number, e.g. the early 001-* / 010-* reports).
  const files = listReportsDir();
  const prefixPadded = String(rowId).padStart(3, '0');
  const prefixRaw    = String(rowId);
  const match = files.find(f =>
    f.startsWith(prefixPadded + '-') || f.startsWith(prefixRaw + '-'),
  );
  return match ? join(REPORTS_DIR, match) : null;
}

// ── Strategy-cache loader (PR #1 popout-overhaul, 2026-05-26) ────────────────
// Reads data/strategy-cache/<rowId>-alignment-*-data-first.json which is
// generated by the data-first popout (right-side drawer drilldown). Carries
// corpus-grounded evidence + open_gaps + reasoning the eval pipeline already
// computed — strictly richer than the cv.md snippet refs the current popout
// surfaces. Tiered cache: callers should treat this as the primary source,
// falling back to report-parsed corpus_snippets only when this is absent.
const STRATEGY_CACHE_DIR = join(ROOT, 'data', 'strategy-cache');
const STRATEGY_CACHE_STALENESS_DAYS = 7;

function loadStrategyCache(rowId) {
  if (!existsSync(STRATEGY_CACHE_DIR)) return null;
  try {
    // Filenames follow `<rowId>-alignment-<slug>-pXXX-fXXX-data-first.json`.
    // Prefer the non-degraded variant (avoid `-alignment---p` empty-slug fallbacks).
    const all = execSync(`ls -1 "${STRATEGY_CACHE_DIR}" 2>/dev/null`, { encoding: 'utf-8', timeout: 5000 })
      .trim().split('\n').filter(Boolean);
    const prefix = String(rowId) + '-alignment-';
    const candidates = all.filter(f => f.startsWith(prefix) && f.endsWith('-data-first.json'));
    if (!candidates.length) return null;
    // Pick the non-empty-slug variant (longest filename = most slug detail).
    candidates.sort((a, b) => b.length - a.length);
    const file = join(STRATEGY_CACHE_DIR, candidates[0]);
    const data = JSON.parse(readFileSync(file, 'utf-8'));
    const now = Date.now();
    const generatedAt = Number(data.generated_at) || 0;
    const ageMs = generatedAt > 0 ? (now - generatedAt) : null;
    const ageDays = ageMs !== null ? Math.floor(ageMs / 86_400_000) : null;
    return {
      evidence:    Array.isArray(data.evidence) ? data.evidence.slice(0, 6) : [],
      open_gaps:   Array.isArray(data.open_gaps) ? data.open_gaps.slice(0, 4) : [],
      reasoning:   data.reasoning || null,
      current:     Number.isFinite(data.current) ? data.current : null,
      ceiling:     Number.isFinite(data.ceiling) ? data.ceiling : null,
      model:       data._model || null,
      generated_at: generatedAt || null,
      age_days:    ageDays,
      is_stale:    ageDays !== null && ageDays > STRATEGY_CACHE_STALENESS_DAYS,
      file,
    };
  } catch { return null; }
}

// ── HM-intel loader (PR #1 popout-overhaul, 2026-05-26) ──────────────────────
// Reads data/hm-intel/<company-role-slug>.json — generated by the hm-intel
// council pipeline. Carries outreach_strategy, alignment_with_goals,
// hiring_managers/recruiters, fit_evidence — all corpus-grounded against
// Mitchell's career arc + the role's specific HM signal.
//
// Lookup strategy: parse company + role from applications.md, slugify, try
// hm-intel/<slug>.json variants. Falls back to null silently when no intel
// has been generated yet (most non-target rows).
function _slugify(s) {
  return String(s || '').toLowerCase()
    .replace(/[^\w\s-]/g, '')
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '');
}

function loadHmIntel(rowId) {
  const APPS = join(REPORTS_DIR, '..', 'data', 'applications.md');
  if (!existsSync(APPS)) return null;
  let company = null, role = null;
  try {
    const text = readFileSync(APPS, 'utf-8');
    // Column 3 = company, column 4 = role
    const rowRe = new RegExp(`^\\|\\s*${rowId}\\s*\\|\\s*[^|]+\\|\\s*([^|]+?)\\s*\\|\\s*([^|]+?)\\s*\\|`, 'm');
    const m = rowRe.exec(text);
    if (!m) return null;
    company = m[1].trim();
    role    = m[2].trim();
  } catch { return null; }
  if (!company || !role) return null;
  const HM_DIR = join(ROOT, 'data', 'hm-intel');
  if (!existsSync(HM_DIR)) return null;
  // Try variants: company-role, company, then any file starting with company-slug
  const companySlug = _slugify(company);
  const roleSlug    = _slugify(role);
  const candidates = [
    `${companySlug}-${roleSlug}.json`,
    `${companySlug}.json`,
  ];
  for (const name of candidates) {
    const path = join(HM_DIR, name);
    if (existsSync(path)) {
      try {
        const data = JSON.parse(readFileSync(path, 'utf-8'));
        return _shapeHmIntel(data, path);
      } catch { /* try next candidate */ }
    }
  }
  // Fallback: glob by company prefix
  try {
    const files = execSync(`ls -1 "${HM_DIR}" 2>/dev/null`, { encoding: 'utf-8', timeout: 3000 })
      .trim().split('\n').filter(Boolean);
    const match = files.find(f => f.startsWith(companySlug + '-') && f.endsWith('.json') && !f.startsWith('_'));
    if (match) {
      const data = JSON.parse(readFileSync(join(HM_DIR, match), 'utf-8'));
      return _shapeHmIntel(data, join(HM_DIR, match));
    }
  } catch { /* fall through */ }
  return null;
}

function _shapeHmIntel(data, file) {
  if (!data) return null;
  const strat = data.outreach_strategy || {};
  return {
    lead_with:       strat.lead_with || null,
    best_first_move: strat.best_first_move || null,
    alignment:       data.alignment_with_goals || null,
    fit_evidence:    Array.isArray(data.fit_evidence) ? data.fit_evidence.slice(0, 3) : [],
    hiring_managers: Array.isArray(data.hiring_managers) ? data.hiring_managers.slice(0, 2) : [],
    recruiters:      Array.isArray(data.recruiters) ? data.recruiters.slice(0, 2) : [],
    file,
  };
}

// ── Tracker-row parser ────────────────────────────────────────────────────────
// 2026-05-26 — Phase E re-evaluation is a tracker-only pipeline. It updates
// applications.md column 5 + the row note (`RE-EVAL <date> (Phase E):
// N/5→N/5 (Δ)`) WITHOUT rewriting the source report file's header. As a
// result, `getProvenance(rowId, 'score')` extracting from the report header
// surfaces a stale score — the popout body disagrees with the chrome strip
// (which sources from the tracker). This helper reads the tracker row + any
// Phase E note so the popout body matches what the rest of the dashboard
// shows.
function parseRowTrackerScore(rowId) {
  const APPS = join(REPORTS_DIR, '..', 'data', 'applications.md');
  if (!existsSync(APPS)) return null;
  try {
    const text = readFileSync(APPS, 'utf-8');
    // Tracker row shape: `| <num> | <date> | <company> | <role> | <score>/5 | <status> | <pdf> | <report-link> | <note> |`
    // Score is the first `\d+(?:\.\d+)?/5` segment after the row marker.
    const rowRe = new RegExp(
      '^\\|\\s*' + rowId + '\\s*\\|\\s*([0-9-]+)\\s*\\|[^|]*\\|[^|]*\\|\\s*(\\d+(?:\\.\\d+)?)\\s*\\/5\\s*\\|[^|]*\\|[^|]*\\|[^|]*\\|\\s*([^|]+?)\\s*\\|',
      'm',
    );
    const m = rowRe.exec(text);
    if (!m) return null;
    const trackerScore = parseFloat(m[2]);
    const date = m[1] || null;
    const note = (m[3] || '').trim();
    // Look for the most recent Phase E re-eval landing score.
    // Format: `RE-EVAL 2026-05-16 (Phase E): 4.1/5→4.1/5` — first `/5` is the
    // landing score after the arrow.
    const phaseEM = note.match(/RE-EVAL\s+(\d{4}-\d{2}-\d{2})\s*\(Phase\s+E\)[^→]*→\s*(\d+(?:\.\d+)?)\s*\/5/i);
    const phaseEScore = phaseEM ? parseFloat(phaseEM[2]) : null;
    const phaseEDate  = phaseEM ? phaseEM[1] : null;
    return {
      trackerScore: Number.isFinite(trackerScore) ? trackerScore : null,
      trackerDate:  date,
      note,
      hasPhaseE:    Boolean(phaseEM),
      phaseEScore:  Number.isFinite(phaseEScore) ? phaseEScore : null,
      phaseEDate,
    };
  } catch { return null; }
}

// ── Report header parser ──────────────────────────────────────────────────────

// Parses the "metadata header" block of a report markdown file:
//   **Score:** 4.6/5
//   **Archetype:** Tier B
//   **Date:** 2026-04-25
//   **URL:** https://...
//   **Legitimacy:** High Confidence
//   **PDF:** pending
//   **Verification:** ...

// BRAVO 2026-05-19 (content sweep): the prior regex expected `**Label**: value`
// (colon AFTER the closing **) but every actual report writes `**Label:** value`
// (colon INSIDE the bold, before the closing **). The old regex never matched
// anything — `parseReportHeader()` returned an empty object — so `header.score`,
// `header.decision`, `header.council`, etc. were all undefined and the popout
// could not render a headline. Now we capture the colon-inside form and strip
// the trailing colon from the key.
const META_RE = /^\*\*([^*]+?):\*\*\s+(.+)$/;
const SCORE_RE = /(\d+(?:\.\d+)?)\/5/;
const GATE_RE  = /GATES?:\s*\[([^\]]+)\]/i;
const PHASE_E_RE = /\(Phase\s+E\)/i;
const RE_EVAL_RE = /Re-eval(?:uated)?\s+(\d{4}-\d{2}-\d{2})/i;

function parseReportHeader(text) {
  const meta = {};
  for (const line of text.split('\n').slice(0, 30)) {
    const m = META_RE.exec(line.trim());
    if (m) meta[m[1].toLowerCase().replace(/\s+/g, '_')] = m[2].trim();
    if (Object.keys(meta).length >= 10) break; // header ends
  }
  return meta;
}

function parsePhaseHistory(text) {
  // Collect all re-eval lines
  const phases = [];
  const lines = text.split('\n');
  for (const line of lines) {
    const reEvalM = RE_EVAL_RE.exec(line);
    if (reEvalM) {
      const scoreM = SCORE_RE.exec(line);
      const gateM  = GATE_RE.exec(line);
      const isPhaseE = PHASE_E_RE.test(line);
      phases.push({
        date:        reEvalM[1],
        score:       scoreM ? parseFloat(scoreM[1]) : null,
        phase_e:     isPhaseE,
        gates_fired: gateM ? gateM[1].split(',').map(s => s.trim()) : [],
      });
    }
  }
  return phases;
}

// ── Git log ───────────────────────────────────────────────────────────────────

function gitLogForFile(filePath) {
  try {
    const raw = execSync(
      `git -C "${ROOT}" log --pretty=format:"%H|%ai|%s" -- "${filePath}" 2>/dev/null`,
      { encoding: 'utf-8', timeout: 5000 },
    ).trim();
    if (!raw) return [];
    return raw.split('\n').map(line => {
      const [sha, date, ...subjectParts] = line.split('|');
      return { sha: sha?.trim(), date: date?.trim(), subject: subjectParts.join('|').trim() };
    }).filter(e => e.sha);
  } catch { return []; }
}

// ── Corpus refs extractor ─────────────────────────────────────────────────────

// Look for "cv.md:N" or "article-digest #N" refs in the report body.
// 2026-05-26 — Council-format reports write line refs as `cv.md:~L18` (tilde-L
// prefix). The prior pattern only matched bare digits and dropped every ref,
// emptying the "What's making this a strong fit" section. The tilde + L are
// both optional so existing `cv.md:18` and `cv.md` (no line) still match.
const CV_REF_RE      = /cv\.md(?::~?L?(\d+))?/g;
const DIGEST_REF_RE  = /article-digest\s*#(\d+)/gi;

function extractCorpusRefs(text) {
  const refs = [];
  let m;
  CV_REF_RE.lastIndex = 0;
  while ((m = CV_REF_RE.exec(text)) !== null) {
    refs.push({ source: 'cv.md', line: m[1] ? parseInt(m[1], 10) : null });
    if (refs.length > 20) break;
  }
  DIGEST_REF_RE.lastIndex = 0;
  while ((m = DIGEST_REF_RE.exec(text)) !== null) {
    refs.push({ source: 'article-digest', entry: parseInt(m[1], 10) });
    if (refs.length > 30) break;
  }
  // Deduplicate
  const seen = new Set();
  return refs.filter(r => {
    const k = JSON.stringify(r);
    if (seen.has(k)) return false;
    seen.add(k);
    return true;
  });
}

// ── Gates from report body ────────────────────────────────────────────────────

// BRAVO 2026-05-19 (content sweep): the prior regex only caught TABLE-format
// gate rows (| H4 | ... | Yes). Council-format reports (Anthropic Applied AI
// Architect row 2059 etc.) write gates in code blocks like:
//   GATES: H4 fired (external enterprise customer-facing tenure required)
// That made every council-format report look like "Gates fired: none" even
// when 2 gates fired. The new regex catches both formats, and we capture the
// human rationale for each gate so the popout can quote the reason.
const HARD_GATE_LINE_RE = /\|\s*(H\d+)[^|]*\|[^|]*\|\s*\**Yes\**\b/gi;
const SOFT_GATE_LINE_RE = /soft\s+gap[:\s]+([^|\n·]+)/gi;
const GATE_CODEBLOCK_RE = /(H\d+)\s+fired\s*(?:\(([^)]+)\))?/gi;
// 2026-05-26 — Council-format reports write fired gates as markdown table rows
// with "FIRES" / "FIRED" in column 2 and the human rationale in column 3 (vs
// the older `H6 fired (reason)` parenthesized form). Without this pattern the
// popout surfaced "no rationale captured in report" while the rationale was
// sitting on disk in column 3.
const HARD_GATE_FIRES_TABLE_RE = /\|\s*(H\d+)[^|]*\|[^|]*?\b(?:FIRES?|fired)\b[^|]*\|\s*([^|\n]+?)\s*\|/gi;
// 2026-05-26 — Body paragraphs like `**H6 note:** H6 fires but is a *flag*...`
// carry the most thorough rationale. Fills failedReasons when neither the
// codeblock parens nor the table column captured a reason. First match wins.
const GATE_BODY_NOTE_RE = /\*\*(H\d+)\s+note:\*\*\s*([^\n]{20,400})/gi;
// Closure 3.10 (2026-05-22) — count gates examined regardless of outcome so
// the popout can say "All N gates cleared" instead of "Evaluation pending"
// when every hard gate returned NO/MONITOR. Pattern: a `| H<n> ... | ... |
// <Yes|No|MONITOR|N/A> |` table row. Bold markers are tolerated.
const ANY_GATE_LINE_RE = /\|\s*(H\d+)[^|]*\|[^|]*\|\s*\**(Yes|No|MONITOR|N\/A|FIRED|—|-)\**/gi;
// Council-format prose: "GATES: none fired" / "GATES fired: none" / "no
// gates fired". Distinguishes "all clear" from "no eval data" so the
// popout can say "All hard gates clear" even when the parser found no
// table-shaped rows.
const NO_GATES_FIRED_RE = /\b(?:GATES?[:\s]*(?:none|no\s+gates?)\s+fired|no\s+gates?\s+fired)\b/i;

function extractGatesFromReport(text) {
  const passed = [], failed = [], failedReasons = {};
  let m;
  HARD_GATE_LINE_RE.lastIndex = 0;
  while ((m = HARD_GATE_LINE_RE.exec(text)) !== null) {
    failed.push(m[1]);
    if (failed.length > 20) break;
  }
  // Council-format: GATES: H4 fired (reason) | H8 fired (reason).
  // BRAVO 2026-05-19 (content sweep): keep ONLY the first rationale per gate.
  // Subsequent occurrences (e.g. "H4 fired (1 gate)" in the composite-override
  // summary block) overwrote the rich rationale with a useless count. First
  // match wins because the primary GATES line appears before the override.
  GATE_CODEBLOCK_RE.lastIndex = 0;
  while ((m = GATE_CODEBLOCK_RE.exec(text)) !== null) {
    if (!failed.includes(m[1])) failed.push(m[1]);
    if (m[2] && !failedReasons[m[1]]) failedReasons[m[1]] = m[2].trim();
    if (failed.length > 20) break;
  }
  // 2026-05-26 — Table-format rationale (column 3 of a markdown gate table).
  // Captures both the gate ID and the human reason when the report uses
  // FIRES/FIRED verbiage in column 2. First match wins so the table reason
  // beats a later codeblock or body-paragraph mention.
  HARD_GATE_FIRES_TABLE_RE.lastIndex = 0;
  while ((m = HARD_GATE_FIRES_TABLE_RE.exec(text)) !== null) {
    if (!failed.includes(m[1])) failed.push(m[1]);
    if (m[2] && !failedReasons[m[1]]) failedReasons[m[1]] = m[2].trim();
    if (failed.length > 20) break;
  }
  // 2026-05-26 — Body-paragraph rationale (`**H6 note:** ...`). Last-resort
  // fill-in when neither codeblock parens nor table column captured a reason.
  GATE_BODY_NOTE_RE.lastIndex = 0;
  while ((m = GATE_BODY_NOTE_RE.exec(text)) !== null) {
    if (!failed.includes(m[1])) failed.push(m[1]);
    if (m[2] && !failedReasons[m[1]]) failedReasons[m[1]] = m[2].trim();
    if (failed.length > 20) break;
  }
  // Closure 3.10 — also enumerate ALL gates the report examined.
  // Any gate seen in a table row but NOT in `failed` counts as passed.
  ANY_GATE_LINE_RE.lastIndex = 0;
  const seen = new Set();
  while ((m = ANY_GATE_LINE_RE.exec(text)) !== null) {
    seen.add(m[1]);
    if (seen.size > 30) break;
  }
  for (const g of seen) {
    if (!failed.includes(g) && !passed.includes(g)) passed.push(g);
  }
  // If no table-shaped gates but the council prose says "none fired",
  // surface that as a pseudo-passed marker so the summary reads correctly.
  if (passed.length === 0 && failed.length === 0 && NO_GATES_FIRED_RE.test(text)) {
    passed.push('all-hard-gates-clear');
  }
  SOFT_GATE_LINE_RE.lastIndex = 0;
  const soft = [];
  while ((m = SOFT_GATE_LINE_RE.exec(text)) !== null) {
    soft.push(m[1].trim());
    if (soft.length > 10) break;
  }
  return { gates_passed: passed, gates_failed: failed, soft_gaps: soft, failed_reasons: failedReasons };
}

// ── cv.md snippet loader ──────────────────────────────────────────────────────
// BRAVO 2026-05-19 (content sweep): the prior provenance card listed bare
// cv.md line numbers (cv.md:19, cv.md:24, ...) which were useless to the
// reader. Now we read the actual text at those lines and return a 1-sentence
// snippet so the popout can show what content actually backs the score.

let _cvCache = null;
function loadCvLines() {
  if (_cvCache) return _cvCache;
  const p = join(ROOT, 'cv.md');
  if (!existsSync(p)) return [];
  try {
    _cvCache = readFileSync(p, 'utf-8').split('\n');
    return _cvCache;
  } catch { return []; }
}

function summarizeCvLine(lineNum) {
  const lines = loadCvLines();
  if (!lines.length || !lineNum || lineNum < 1) return null;
  // Read the cited line + up to 2 following lines until we hit a blank or
  // 200 chars. Strip markdown bullet / bold markers. Return the first sentence.
  const idx = lineNum - 1;
  if (idx >= lines.length) return null;
  let chunk = (lines[idx] || '').trim();
  // If the cited line is empty, peek at the next non-empty line.
  let peek = idx;
  while (!chunk && peek < lines.length - 1) {
    peek++;
    chunk = (lines[peek] || '').trim();
  }
  if (!chunk) return null;
  // If the line is a markdown heading, return it bare (no further joining)
  if (/^#+\s/.test(chunk)) {
    return chunk.replace(/^#+\s+/, '').replace(/\*\*/g, '').trim().slice(0, 200);
  }
  // Otherwise join up to 2 continuation lines while the next line is also content
  for (let i = peek + 1; i < Math.min(peek + 3, lines.length); i++) {
    const next = (lines[i] || '').trim();
    if (!next) break;
    if (/^[*#-]/.test(next) && !chunk.match(/[,;:—]\s*$/)) break;
    chunk += ' ' + next;
    if (chunk.length > 300) break;
  }
  // Clean markdown noise
  chunk = chunk
    .replace(/^\s*[-*]\s+/, '')           // leading bullet
    .replace(/\*\*([^*]+)\*\*/g, '$1')    // bold
    .replace(/`([^`]+)`/g, '$1')          // inline code
    .replace(/<!--[^>]*-->/g, '')         // HTML comments
    .replace(/\s+/g, ' ')
    .trim();
  // First sentence (or first 220 chars).
  const sentMatch = chunk.match(/^[^.!?]{20,220}[.!?]/);
  return (sentMatch ? sentMatch[0] : chunk.slice(0, 220)).trim();
}

