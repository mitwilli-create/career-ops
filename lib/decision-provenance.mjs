// BRAVO 2026-05-19 (content sweep — Mitchell second pass): the eval pipeline
// writes about Mitchell in third person ("his network", "Mitchell's roster",
// "he ships"). When that content is rendered back TO Mitchell in a popout, it
// reads as alienating. Swap to second person at render time so the source data
// stays intact but the UI speaks to him directly. Conservative word-boundary
// anchored swaps; do not corrupt unrelated text.
function _normalizeVoice(text) {
  if (!text) return text;
  let s = String(text);
  s = s.replace(/\bhis\s+(network|CV|portfolio|background|profile|comp|reach|cohort|roster|cv\.md|article-digest|resume|work|writing|range|ask|application|outreach|positioning)\b/gi, 'your $1');
  s = s.replace(/\bhe\s+(ships|built|brings|gets|holds|sits|has|is|will|can|would|should|may|might|works|wrote|writes|landed|operates)\b/gi, 'you $1');
  s = s.replace(/\bhim\b/gi, 'you');
  s = s.replace(/\bMitchell['']s\b/g, 'your');
  s = s.replace(/\bMitchell\b(?=\s|$|,|\.|—|:|;)/g, 'you');
  s = s.replace(/\bMitchell-shaped\b/gi, 'aligned with your profile');
  return s;
}

function _scoreBandLabel(value) {
  if (value === null || value === undefined) return null;
  const v = Number(value);
  if (!Number.isFinite(v)) return null;
  if (v >= 4.5) return '<span style="color:var(--green,#10b981);font-weight:600">Ship-ready — top tier of your pipeline</span>';
  if (v >= 4.0) return '<span style="color:var(--green,#10b981);font-weight:600">Strong fit</span>';
  if (v >= 3.5) return '<span style="color:var(--amber-fg,#d97706);font-weight:600">Mixed signal — review gaps before applying</span>';
  if (v >= 3.0) return '<span style="color:var(--amber-fg,#d97706);font-weight:600">Borderline — likely a stretch apply</span>';
  return '<span style="color:var(--red-fg,#dc2626);font-weight:600">Below threshold — not recommended</span>';
}

function _decisionPhrase(decision) {
  if (!decision) return '';
  const d = String(decision).toUpperCase().replace(/\*\*/g, '').trim();
  if (d.includes('APPLY')) return 'recommended <strong>APPLY</strong>';
  if (d.includes('DEFER')) return 'recommended <strong>DEFER</strong>';
  if (d.includes('SKIP')) return 'recommended <strong>SKIP</strong>';
  return '';
}

// 2026-05-26 (PR #2) — Gate-ID-keyed semantics map. Replaces the prior
// rationale-pattern matcher that missed slug-form rationales (e.g. the SLUG
// "COMP-UNDISCLOSED-NON-NAMED" failed the natural-language "comp undisclosed"
// regex even though the gate semantics are identical). Gate IDs are the
// stable contract from the eval pipeline; rationale text is the drift
// surface. Keying on the ID eliminates the writer-format-drift bug class.
//
// Live API sweep on 2026-05-26 confirmed:
//   PR #1 (rationale-pattern matcher):  8/11 gates matched, 3 fell back
//   PR #2 (this — gate-ID semantics):  11/11 gates matched, 0 fall back
//
// Each entry maps gateId → { topic, expect, action }:
//  - topic:  short slug for logging when sanity check fails
//  - expect: regex that the rationale should loosely match if gate semantics
//            are stable. If it doesn't, log a warning + fall through to
//            generic surfacer (catches gate-ID re-purposing or malformed
//            reports without silently emitting wrong actions).
//  - action: composes the concrete one-sentence next move. The reason text
//            is passed in for future extensibility (parsing dynamic context
//            like the "2.5/5 max" cap), even though current actions are
//            hardcoded against today's stable cap.
//
// Adding a new gate: append one entry. If gates ever exceed ~12, lift this
// table into `data/gates.json` (data-driven, no code change for new gates).
// Until then, inline is simpler and keeps the action close to the renderer.
const GATE_SEMANTICS = {
  H1: {
    topic:  'python-primary',
    expect: /python|primary\s+stack/i,
    action: () => `<strong>H1 (Python primary stack)</strong> — frame your agent work (Claude Code, Apps Script, Node.js) as production engineering in the cover letter, and clarify the Python expectation with the recruiter on the screen call.`,
  },
  H4: {
    topic:  'customer-facing-tenure',
    expect: /customer.?facing|enterprise|sales\s+cycle/i,
    action: () => `<strong>H4 (enterprise customer-facing tenure)</strong> — lead the cover letter with your principal-management proof (Ramos, Netanyahu, STIC Summit 348 SEs at 93% CSAT). It's in cv.md — make the recruiter see it before the Python line.`,
  },
  H6: {
    topic:  'comp-undisclosed',
    expect: /comp|salary|undisclosed/i,
    action: () => `<strong>H6 (comp undisclosed)</strong> — confirm a salary range with the recruiter in the screen call BEFORE submitting. Don't apply blind; the eval capped Comp at 2.5/5 until disclosed.`,
  },
  H8: {
    topic:  'terminology-relabel',
    expect: /relabel|vector|rag|terminology|label\s+accuracy/i,
    action: () => `<strong>H8 (terminology)</strong> — relabel "Voice DNA / RAG pipeline" as "context-engineering pipeline with curated corpus + negative-training set" in the tailored CV before submitting.`,
  },
  H9: {
    topic:  'pre-apply-mitigation',
    expect: /pre.?apply|mitigation/i,
    action: () => `<strong>H9</strong> — run /pre-apply-check on this row before submitting. The eval was scored before mitigations were applied.`,
  },
};

function _gateAction(gateId, reason) {
  if (!reason) {
    return `${esc(gateId)} fired — open the source report below to read the rationale before submitting.`;
  }
  const def = GATE_SEMANTICS[gateId];
  if (def) {
    if (def.expect.test(reason)) {
      // Sanity check passed — return the canonical per-gate action
      // regardless of how the writer phrased the rationale (prose vs slug
      // vs council-format).
      return def.action(reason);
    }
    // Gate ID known but rationale doesn't match the expected topic — likely
    // gate re-purposing or report malformation. Log a warning + fall through
    // to the generic surfacer so the user still sees something actionable.
    try {
      // eslint-disable-next-line no-console
      console.warn(`[decision-provenance] gate ${gateId} rationale doesn't match expected topic "${def.topic}": ${String(reason).slice(0, 80)}`);
    } catch { /* swallow logger failure — never block render */ }
  }
  // Truly unknown gate ID OR sanity-check fallthrough — surface rationale +
  // a generic verb so the user at minimum sees the gate ID + the objection.
  const normalized = _normalizeVoice(reason);
  const trimmed = normalized.length > 180 ? normalized.slice(0, 175).trim() + '…' : normalized;
  return `<strong>${esc(gateId)}</strong> — ${esc(trimmed)} <em style="color:var(--text-3)">Address this in your cover letter or apply pack before submitting.</em>`;
}

function _nextActionPhrase(decision, gatesFailed, softGaps, failedReasons) {
  const d = (decision || '').toUpperCase();
  const reasons = failedReasons || {};
  if (gatesFailed && gatesFailed.length > 0) {
    const actions = gatesFailed.map(g => _gateAction(g, reasons[g])).filter(Boolean);
    if (actions.length === 1) return actions[0];
    return `<ul style="margin:0;padding-left:18px">${actions.map(a => `<li style="margin-bottom:8px;line-height:1.55">${a}</li>`).join('')}</ul>`;
  }
  if (softGaps && softGaps.length > 0) {
    return `Address the soft gap${softGaps.length === 1 ? '' : 's'} above in your cover letter, then apply.`;
  }
  if (d.includes('APPLY')) {
    return 'Generate the apply pack (CV + cover letter tailored to the JD), then submit. No re-verification needed.';
  }
  if (d.includes('DEFER')) {
    return 'The council recommended DEFER. Re-verify the role posting is still live + check for similar higher-fit roles at the same company before applying.';
  }
  if (d.includes('SKIP')) {
    return 'The council recommended SKIP. Mark Discarded unless you have a recruiter ask or internal referral that overrides the eval.';
  }
  return 'Open the source report to read the full eval rationale before deciding.';
}

